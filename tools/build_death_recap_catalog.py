#!/usr/bin/env python3
"""Emit bounded personal catalog data from the reviewed independent API audit."""
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def lua(value):
    if value is True:return 'true'
    if value is False:return 'false'
    if value is None:return 'nil'
    if isinstance(value,str):return json.dumps(value,ensure_ascii=False)
    if isinstance(value,(int,float)):return str(value)
    if isinstance(value,list):return '{'+','.join(lua(v) for v in value)+'}'
    return '{'+','.join('['+lua(k)+']='+lua(v) for k,v in sorted(value.items(),key=lambda p:str(p[0])))+'}'


def build():
    path=ROOT/'provenance/death-recap/catalog.json';raw=path.read_bytes();data=json.loads(raw)
    supplies=json.loads((path.parent/'consumables.json').read_text())
    fields=['key','spellID','name','category','role','class','specs','knownSpellIDs','verified','requiredTalentSpellIDs']
    entries=[{k:e[k] for k in fields if k in e} for e in data['entries'] if e['verified'] is True]
    spells={i:True for e in supplies['entries'] if e['verified'] for i in e['useSpellIDs']}
    item_names={i:e['name'] for e in supplies['entries'] if e['verified'] for i in e['useSpellIDs']}
    item_kinds={i:e['category'] for e in supplies['entries'] if e['verified'] for i in e['useSpellIDs']}
    result={'revision':data['revision'],'build':data['build'],'coverageComplete':False,'entries':entries,'itemUseSpells':spells,'itemUseNames':item_names,'itemUseKinds':item_kinds,'journal':{}}
    return '-- Independently authored facts; classification is a product convention, not readiness.\n-- Generated by tools/build_death_recap_catalog.py; audit SHA256 '+hashlib.sha256(raw).hexdigest()+'.\nlocal _, RA = ...\nRA.DeathRecapCatalog = '+lua(result)+'\n'


if __name__=='__main__':
    (ROOT/'RCPArsenal/DeathRecapCatalog.lua').write_text(build())
